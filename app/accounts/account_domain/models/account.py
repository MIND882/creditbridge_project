"""

Account -- converted from ``erpnext/accounts/doctype/account``.



Field mapping (account.json -> SQLAlchemy), with the two structural changes

the conversion requires:



JSON field            Type here                Notes

--------------------  -----------------------  -----------------------------

account_name          String(140) NOT NULL     reqd=1

account_number        String(140)              unique with business_id

is_group              Boolean default False    group vs ledger

company               *collapsed*              see note below

root_type             Enum(RootType)

report_type           Enum(ReportType)

account_currency      String(140)

parent_account        parent_account_id UUID   self-FK, nullable = root

account_type          Enum(AccountType)

tax_rate              Numeric(21,9)            Float -> Numeric(21,9)

freeze_account        Enum(FreezeAccount)

balance_must_be       Enum(BalanceMustBe)

lft / rgt             *omitted*                adjacency list replaces NestedSet

old_parent            *omitted*                NestedSet renumbering artifact

include_in_gross      Boolean

disabled              Boolean

account_category      String(140)              Link by label (see note below)



**``company``.** ERPNext scopes Accounts by Company, and a site may hold

several companies. CreditBridge's tenant *is* the business, and there is no

Company doctype in this conversion, so ``company`` collapses into

``business_id``. Every per-company check upstream therefore becomes a

per-tenant check. If a Company doctype is converted later, add ``company_id``

here and re-scope the repository -- the service's validation shape does not

change.



**``account_category``.** Stored as the label, not a FK, to match ERPNext's

Link-by-name. The service resolves it through

``AccountCategoryService.root_type_for``, which returns ``None`` for an unknown

label rather than raising, so a stale imported label cannot block creation.

"""



from __future__ import annotations



import uuid

from decimal import Decimal

from typing import Optional



from sqlalchemy import (

    Boolean,

    ForeignKey,

    Index,

    Numeric,

    String,

    UniqueConstraint,

)

from sqlalchemy import Enum as SAEnum

from sqlalchemy.orm import Mapped, mapped_column, relationship



from app.accounts.enums import (

    AccountType,

    BalanceMustBe,

    FreezeAccount,

    ReportType,

    RootType,

)

from app.core.base_model import TenantModel, tenant_index



__all__ = ["Account"]





class Account(TenantModel):

    """

    One node of a tenant's chart of accounts.



    ``is_group=True`` means the node may have children (a Frappe "Group");

    ``False`` means it is a posting target (a "Ledger"). That distinction is

    the spine of the validation in ``AccountService``.

    """



    __tablename__ = "accounts"

    __table_args__ = (

        # ERPNext's autoname ("number - name - COMPANY") is unique per company;

        # the tenant takes the place of the company here.

        UniqueConstraint("business_id", "name", name="uq_accounts_business_id_name"),

        # Port of validate_account_number(): account_number may not repeat

        # within a company. Partial-enforced in the service because NULL must

        # stay allowed for accounts with no number.

        Index("ix_accounts_business_number", "business_id", "account_number"),

        # The tree walk is always (business_id, parent_account_id).

        tenant_index("ix_accounts_business_parent", "parent_account_id"),

        # Mirrors `on_doctype_update()` in account.py, which adds [lft, rgt];

        # the adjacency-list equivalent indexes the parent pointer instead.

        tenant_index("ix_accounts_business_is_group", "is_group"),

    )



    # ── identity / naming ────────────────────────────────────────────────────

    #: The ERPNext document `name` -- a human label, generated by

    #: ``get_account_autoname``. Kept unique per tenant so migrated references

    #: by name still resolve.

    name: Mapped[str] = mapped_column(String(255), nullable=False)



    account_name: Mapped[str] = mapped_column(String(140), nullable=False)

    account_number: Mapped[Optional[str]] = mapped_column(String(140), nullable=True)



    # ── tree ─────────────────────────────────────────────────────────────────

    #: Adjacency-list parent. ``None`` marks a root node.

    parent_account_id: Mapped[Optional[uuid.UUID]] = mapped_column(

        ForeignKey("accounts.id", ondelete="RESTRICT"),

        nullable=True,

        index=True,

    )



    parent_account: Mapped[Optional["Account"]] = relationship(

        "Account",

        remote_side="Account.id",

        back_populates="children",

        foreign_keys=[parent_account_id],

    )

    children: Mapped[list["Account"]] = relationship(

        "Account",

        back_populates="parent_account",

        foreign_keys=[parent_account_id],

        passive_deletes=True,

    )



    is_group: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)



    # ── classification ───────────────────────────────────────────────────────

    root_type: Mapped[Optional[RootType]] = mapped_column(

        SAEnum(RootType, native_enum=False, length=20, validate_strings=True), nullable=True

    )

    report_type: Mapped[Optional[ReportType]] = mapped_column(

        SAEnum(ReportType, native_enum=False, length=20, validate_strings=True), nullable=True

    )

    account_type: Mapped[Optional[AccountType]] = mapped_column(

        SAEnum(AccountType, native_enum=False, length=60, validate_strings=True), nullable=True

    )



    # ── money / currency ─────────────────────────────────────────────────────

    account_currency: Mapped[Optional[str]] = mapped_column(String(140), nullable=True)



    #: ERPNext `Float` -> Numeric(21,9). Float is binary and loses cents;

    #: every money-adjacent column in this conversion is exact-decimal.

    tax_rate: Mapped[Optional[Decimal]] = mapped_column(Numeric(21, 9), nullable=True)



    balance_must_be: Mapped[Optional[BalanceMustBe]] = mapped_column(

        SAEnum(BalanceMustBe, native_enum=False, length=10, validate_strings=True), nullable=True

    )

    freeze_account: Mapped[Optional[FreezeAccount]] = mapped_column(

        SAEnum(FreezeAccount, native_enum=False, length=10, validate_strings=True), nullable=True

    )



    # ── flags ────────────────────────────────────────────────────────────────

    include_in_gross: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)

    disabled: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)



    # ── link by label ────────────────────────────────────────────────────────

    account_category: Mapped[Optional[str]] = mapped_column(String(140), nullable=True)



    def __repr__(self) -> str:  # pragma: no cover - debugging aid

        return f"<Account id={self.id} name={self.name!r} is_group={self.is_group}>"
